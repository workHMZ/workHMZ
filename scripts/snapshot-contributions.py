#!/usr/bin/env python3
"""Snapshot the public contribution calendar into a small JS data file.

The portfolio page is static, so the calendar card reads this snapshot instead of
calling an API from the visitor's browser. Past years never change; rerun this to
refresh the current year.

    python3 scripts/snapshot-contributions.py [calendar-data.js]

Requires an authenticated `gh` CLI. Only public contribution levels are stored.
"""
from datetime import date
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]

LOGIN = 'workHMZ'
FIRST_YEAR = 2020
LEVELS = {'NONE': '0', 'FIRST_QUARTILE': '1', 'SECOND_QUARTILE': '2',
          'THIRD_QUARTILE': '3', 'FOURTH_QUARTILE': '4'}
QUERY = '''query($login:String!,$from:DateTime!,$to:DateTime!){
  user(login:$login){contributionsCollection(from:$from,to:$to){
    contributionCalendar{totalContributions weeks{contributionDays{
      date contributionLevel weekday}}}}}}'''


def fetch(year, today_iso):
    result = subprocess.run(
        ['gh', 'api', 'graphql', '-f', f'query={QUERY}', '-f', f'login={LOGIN}',
         '-f', f'from={year}-01-01T00:00:00Z', '-f', f'to={year}-12-31T23:59:59Z'],
        check=True, capture_output=True, text=True)
    calendar = json.loads(result.stdout)['data']['user']['contributionsCollection']['contributionCalendar']
    weeks = calendar['weeks']
    # Seven strings, Sunday first. Space = outside the year; '.' = future date after today.
    rows = [[' '] * len(weeks) for _ in range(7)]
    for column, week in enumerate(weeks):
        for day in week['contributionDays']:
            if day['date'] > today_iso:
                rows[day['weekday']][column] = '.'
            else:
                rows[day['weekday']][column] = LEVELS[day['contributionLevel']]
    return {'total': calendar['totalContributions'], 'rows': [''.join(row) for row in rows]}


def main():
    if len(sys.argv) > 2:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    output = Path(sys.argv[1]) if len(sys.argv) == 2 else (ROOT / 'calendar-data.js')
    today = date.today()
    today_iso = today.isoformat()
    years = {str(year): fetch(year, today_iso) for year in range(FIRST_YEAR, today.year + 1)}
    lines = [
        f'/* Generated by scripts/snapshot-contributions.py on {today.isoformat()}. Do not edit by hand. */',
        'window.CALENDAR = {',
        f"  asOf: '{today.isoformat()}',",
        '  years: {',
    ]
    for year, data in years.items():
        lines.append(f"    {year}: {{ total: {data['total']}, rows: [")
        lines.extend(f"      '{row}'," for row in data['rows'])
        lines.append('    ] },')
    lines += ['  }', '};', '']
    output.write_text('\n'.join(lines), encoding='utf-8')
    summary = ', '.join('{} ({})'.format(year, data['total']) for year, data in years.items())
    print(f'Wrote {output}: {summary}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
